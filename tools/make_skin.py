#!/usr/bin/env python3
"""Generate ``skins/cuttlefish.yaml`` from ``packages/core/tokens.json`` (the only source of colour).

    python3 tools/make_skin.py            write the skin
    python3 tools/make_skin.py --check    exit 1 if the committed file differs from what tokens.json produces

D2: the skin carries NO ``background`` key and no ground colour of any kind. In the TUI a skin background drives
OSC 11 (a full-window repaint); here your terminal's own background shows through. Only foreground accents are set,
from the identity arc at the three dot lightness tiers. Stdlib only."""
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "packages" / "core" / "tokens.json"
OUT = ROOT / "skins" / "cuttlefish.yaml"


def _oklab():
    spec = importlib.util.spec_from_file_location("_cf_oklab", ROOT / "color" / "oklab.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["_cf_oklab"] = mod
    spec.loader.exec_module(mod)
    return mod


def build():
    """(name, description, colors): colors is an ordered dict of skin key -> '#rrggbb'. Foreground only."""
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    ok = _oklab()
    ident = t["identity"]
    hue = sum(ident["hue_arc_deg"]) / 2          # the arc's middle: one representative hue for a static file
    lo, mid, hi = ident["dot_lightness"]
    c = ident["dot_chroma"]

    def hx(L):
        return ok.oklch_to_hex(ok.OKLCh(L, c, hue)).lower()

    colors = {
        "banner_title": hx(hi), "banner_accent": hx(mid), "banner_border": hx(lo), "banner_dim": hx(lo),
        "ui_accent": hx(mid), "ui_label": hx(hi), "input_rule": hx(lo), "response_border": hx(mid),
        "session_label": hx(hi), "status_bar_strong": hx(mid),
    }
    return "cuttlefish", "Sparse identity dots on your own background (no background colour is set)", colors


def render():
    name, desc, colors = build()
    lines = ["# GENERATED by tools/make_skin.py from packages/core/tokens.json: do not edit.",
             "# No `background` key on purpose: a skin background makes the TUI paint OSC 11 over the whole window.",
             "name: %s" % name, 'description: "%s"' % desc, "colors:"]
    lines += ['  %s: "%s"' % (k, v) for k, v in colors.items()]
    return "\n".join(lines) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if have != text:
            print("skins/cuttlefish.yaml is %s; run: python3 tools/make_skin.py" % ("missing" if have is None else "stale"))
            return 1
        print("skins/cuttlefish.yaml is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print("wrote %s" % OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
