#!/usr/bin/env node
// Generate domain/tokens.ts from the frozen tokens.json (bundles must be import-free, so the
// constants are inlined). `--check` exits 1 if the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const json = JSON.parse(readFileSync(new URL('tokens.json', root), 'utf8'));
const out =
`// GENERATED by tools/gen-tokens.mjs from packages/core/tokens.json: do not edit by hand.
// Inlined (not imported) so the committed bundles stay import-free. Deeply frozen.

function freeze<T>(o: T): T {
  if (o && typeof o === 'object') for (const v of Object.values(o)) freeze(v);
  return Object.freeze(o);
}

export const TOKENS = freeze(${JSON.stringify(json, null, 2)} as const);
`;
const target = new URL('domain/tokens.ts', root);
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(target, 'utf8'); } catch {}
  if (cur !== out) { console.error('domain/tokens.ts is stale: run node tools/gen-tokens.mjs'); process.exit(1); }
  console.log('tokens.ts fresh');
} else {
  writeFileSync(target, out);
  console.log('wrote ' + fileURLToPath(target));
}
