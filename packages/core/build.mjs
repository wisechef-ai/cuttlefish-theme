// Builds the SAME entry (index.ts) into the two committed, self-contained, import-free ESM bundles:
//   desktop/core.bundle.js   (browser, es2022)  -> inlined by the desktop plugin (its loader resolves only @hermes/plugin-sdk/react)
//   tui/core.bundle.mjs      (node, node22)     -> imported by the TUI widget
// Deterministic: no timestamps, no absolute paths (esbuild comments are relative to this directory), no legal comments.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const HEADER = '// GENERATED by packages/core/build.mjs from packages/core — do not edit';

export const TARGETS = [
  { rel: 'desktop/core.bundle.js', platform: 'browser', target: 'es2022' },
  { rel: 'tui/core.bundle.mjs', platform: 'node', target: 'node22' },
];

/** Build every target in memory: [{ rel, text }] (rel is relative to the repo root). */
export async function buildAll() {
  const out = [];
  for (const t of TARGETS) {
    const r = await build({
      absWorkingDir: here, entryPoints: ['index.ts'], bundle: true, format: 'esm', platform: t.platform, target: t.target,
      legalComments: 'none', write: false, logLevel: 'silent', charset: 'utf8', banner: { js: HEADER },
    });
    out.push({ rel: t.rel, text: r.outputFiles[0].text });
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const { rel, text } of await buildAll()) {
    const path = `${here}/../../${rel}`;
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    console.log(`${rel}  ${Buffer.byteLength(text)} bytes`);
  }
}
