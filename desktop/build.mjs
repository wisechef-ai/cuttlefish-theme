#!/usr/bin/env node
// Builds desktop/plugin.js: the ONE self-contained ESM file the desktop loads.
// TypeScript types are stripped with node's own stripper; the remaining ES
// modules are wrapped into a lazy registry so the output imports NOTHING but
// the three specifiers a disk plugin may import (@hermes/plugin-sdk, react,
// react/jsx-runtime). Deterministic by construction: no timestamps, modules
// emitted in name order, externals in a fixed order — the same tree always
// bytes to the same file, which is what `--check` (and the shipped-artifact
// discipline) relies on.
//
//   node desktop/build.mjs          write desktop/plugin.js (via temp + rename)
//   node desktop/build.mjs --check  exit 1 with a diff if it would differ
import { readFileSync, writeFileSync, renameSync, unlinkSync } from 'node:fs'
import { stripTypeScriptTypes } from 'node:module'
import { dirname, join, normalize, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)))
const ENTRY = 'src/index.ts'
const OUT = 'plugin.js'
const EXTERNALS = ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime']
const EXT_IDS = { '@hermes/plugin-sdk': '__cf_sdk', react: '__cf_react', 'react/jsx-runtime': '__cf_jsx' }
const HEADER = '// GENERATED by desktop/build.mjs — the shipped cuttlefish-theme plugin. Do not edit; rebuild with `node desktop/build.mjs`.'

const fail = (msg) => {
  console.error(`build.mjs: ${msg}`)
  process.exit(1)
}

/** `a/b/c.ts` importing `../d.ts` -> `a/d.ts`; bare specifiers must be known externals. */
function resolveFrom(from, spec) {
  if (!spec.startsWith('.')) {
    if (!EXTERNALS.includes(spec)) fail(`module ${from} imports ${spec}: only ${EXTERNALS.join(', ')} are allowed`)
    return { external: spec }
  }
  return { local: normalize(join(dirname(from), spec)) }
}

/** One named-import clause `a, b as c` -> the destructuring entries. */
function bindingsOf(clause) {
  return clause.split(',').map(s => s.trim()).filter(s => s.length > 0).map(s => {
    const m = /^([\w$]+)(?:\s+as\s+([\w$]+))?$/.exec(s)
    if (!m) fail(`unsupported import entry "${s}"`)
    return { imported: m[1], local: m[2] ?? m[1] }
  })
}

const destructured = (entries, source) =>
  `const { ${entries.map(e => (e.local === e.imported ? e.local : `${e.imported}: ${e.local}`)).join(', ')} } = ${source}` + ';'

/**
 * Rewrite one stripped module body into a plain function body. Returns
 * { body, exports: [{name, local}], deps: [module names] }; fails loudly on any
 * statement form this builder does not pin (so an edit cannot silently change
 * what ships).
 */
function transformModule(name, stripped) {
  const deps = []
  const exports = []
  let hasDefault = false
  let text = stripped

  const noteDep = (spec) => {
    const r = resolveFrom(name, spec)
    if (r.local) deps.push(r.local)
    return r
  }

  // import … from '…' — namespace, default, named (the only three forms used)
  text = text.replace(/^import\s+\*\s+as\s+([\w$]+)\s+from\s*['"]([^'"]+)['"]\s*;?/gm, (_m, local, spec) => {
    const r = noteDep(spec)
    return `const ${local} = ${r.external ? `__cf_ext(${JSON.stringify(r.external)})` : `__cf_require(${JSON.stringify(r.local)})`};`
  })
  text = text.replace(/^import\s+([\w$]+)\s+from\s*['"]([^'"]+)['"]\s*;?/gm, (_m, local, spec) => {
    const r = noteDep(spec)
    const source = r.external ? `__cf_ext(${JSON.stringify(r.external)})` : `__cf_require(${JSON.stringify(r.local)})`
    return `const ${local} = ${source}.default;`
  })
  text = text.replace(/^import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]\s*;?/gm, (_m, clause, spec) => {
    const r = noteDep(spec)
    const source = r.external ? `__cf_ext(${JSON.stringify(r.external)})` : `__cf_require(${JSON.stringify(r.local)})`
    return destructured(bindingsOf(clause), source)
  })
  text = text.replace(/^import\s*['"][^'"]+['"]\s*;?/gm, () => '')   // side-effect import: nothing to do at bundle time

  // export …
  if (/^export\s*\*/m.test(text)) fail(`${name}: \`export *\` is not supported`)
  text = text.replace(/^export\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]\s*;?/gm, (_m, clause, spec) => {
    const r = noteDep(spec)
    if (r.external) fail(`${name}: re-export from an external (${spec}) is not supported`)
    const entries = bindingsOf(clause)
    for (const e of entries) exports.push(e)
    return destructured(entries, `__cf_require(${JSON.stringify(r.local)})`)
  })
  text = text.replace(/^export\s*\{([^}]*)\}\s*;?/gm, (_m, clause) => {
    for (const e of bindingsOf(clause)) exports.push(e)
    return ''
  })
  if (/^export\s+default\s+/m.test(text)) {
    text = text.replace(/^export\s+default\s+/m, () => { hasDefault = true; return 'const __cf_default = ' })
  }
  text = text.replace(/^export\s+(async\s+function\s*\*?\s*|function\s*\*?\s*|(?:const|let|var|class)\s+)([\w$]+)/gm,
    (_m, keyword, local) => {
      exports.push({ imported: local, local })
      return keyword + local
    })

  const leftover = /^(?:import|export)\b/m.exec(text)
  if (leftover) fail(`${name}: an unsupported ${leftover[0]} statement survived the transform`)
  const exportList = hasDefault ? [...exports, { imported: 'default', local: '__cf_default' }] : exports
  return { body: text, exports: exportList, deps }
}

/** Walk the import graph from the entry, stripping + transforming each module once. */
function build() {
  const modules = new Map()
  const visiting = new Set()
  const load = (name) => {
    if (modules.has(name)) return
    if (visiting.has(name)) fail(`import cycle through ${name}`)
    visiting.add(name)
    const stripped = stripTypeScriptTypes(readFileSync(join(ROOT, name), 'utf8'), { mode: 'strip' })
    const { body, exports, deps } = transformModule(name, stripped)
    modules.set(name, { body, exports })
    for (const dep of deps) load(dep)
    visiting.delete(name)
  }
  load(ENTRY)

  const lines = [HEADER]
  for (const spec of EXTERNALS) lines.push(`import * as ${EXT_IDS[spec]} from ${JSON.stringify(spec)};`)
  lines.push('')
  lines.push('const __cf_ext = (spec) => {')
  for (const spec of EXTERNALS) lines.push(`  if (spec === ${JSON.stringify(spec)}) return ${EXT_IDS[spec]};`)
  lines.push('  throw new Error("cuttlefish-theme: unsupported import " + spec);')
  lines.push('};')
  lines.push('const __cf_defs = Object.create(null);')
  lines.push('const __cf_cache = Object.create(null);')
  lines.push('const __cf_require = (name) => {')
  lines.push('  const hit = __cf_cache[name];')
  lines.push('  if (hit !== undefined) return hit;')
  lines.push('  const def = __cf_defs[name];')
  lines.push('  if (def === undefined) throw new Error("cuttlefish-theme: no module " + name);')
  lines.push('  const exports = Object.create(null);')
  lines.push('  __cf_cache[name] = exports;')
  lines.push('  def(exports);')
  lines.push('  return exports;')
  lines.push('};')
  lines.push('')
  for (const name of [...modules.keys()].sort()) {
    const { body, exports } = modules.get(name)
    lines.push(`__cf_defs[${JSON.stringify(name)}] = (exports) => {`)
    lines.push(body.replace(/\s+$/m, ''))
    if (exports.length > 0) {
      const list = exports.map(e => (e.local === e.imported ? e.local : `${e.imported}: ${e.local}`)).join(', ')
      lines.push(`Object.assign(exports, { ${list} });`)
    }
    lines.push('};')
    lines.push('')
  }
  lines.push(`export default __cf_require(${JSON.stringify(ENTRY)}).default;`)
  lines.push('')
  return lines.join('\n')
}

const wanted = build()
const outPath = join(ROOT, OUT)
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(outPath, 'utf8') } catch { fail(`${OUT} does not exist`) }
  if (current !== wanted) {
    fail(`${OUT} is stale: run \`node desktop/build.mjs\` and commit the result`)
  }
  console.log(`build.mjs: ${OUT} is up to date (${wanted.length} bytes)`)
  process.exit(0)
}
const tmp = join(ROOT, `${OUT}.tmp`)
try {
  writeFileSync(tmp, wanted)
  try { unlinkSync(outPath) } catch { /* first build */ }
  renameSync(tmp, outPath)
} catch (e) {
  fail(`could not write ${OUT}: ${String(e)}`)
}
console.log(`build.mjs: wrote ${OUT} (${wanted.length} bytes, ${process.argv[2] ?? 'src/index.ts'})`)
